    /// Bir ozellik vektorunu siniflandirir.
    ///
    /// Adimlar `hydration_model.h` ile ayni:
    /// 1. z-skoru,
    /// 2. en yakin K komsu (karesel Oklit uzakligi),
    /// 3. 1/(d^2+eps) agirlikli oylama,
    /// 4. WNI = 100 * (0.5*P(MODERATE) + 1.0*P(HIGH)).
    static func predict(features: [Double]) -> HydrationPrediction? {
        guard features.count == featureCount else { return nil }

        var z = [Double](repeating: 0, count: featureCount)
        for j in 0..<featureCount {
            let denom = featureStd[j] > 1e-9 ? featureStd[j] : 1
            z[j] = (features[j] - featureMean[j]) / denom
        }

        // En kucuk K karesel uzakligi sirali tut.
        var bestDist2 = [Double](repeating: .greatestFiniteMagnitude, count: k)
        var bestLabel = [Int](repeating: 0, count: k)

        for i in 0..<trainingZ.count {
            var d2 = 0.0
            for j in 0..<featureCount {
                let diff = z[j] - trainingZ[i][j]
                d2 += diff * diff
            }
            for slot in 0..<k where d2 < bestDist2[slot] {
                var m = k - 1
                while m > slot {
                    bestDist2[m] = bestDist2[m - 1]
                    bestLabel[m] = bestLabel[m - 1]
                    m -= 1
                }
                bestDist2[slot] = d2
                bestLabel[slot] = trainingLabel[i]
                break
            }
        }

        var score = [0.0, 0.0, 0.0]
        for slot in 0..<k {
            // Agirlik = 1 / (d^2 + eps)
            score[bestLabel[slot]] += 1.0 / (bestDist2[slot] + 0.001)
        }

        let sum = score.reduce(0, +)
        guard sum > 0 else { return nil }

        let probability = score.map { $0 / sum }
        var bestClass = 0
        for c in 1..<3 where probability[c] > probability[bestClass] { bestClass = c }

        let wni = 100 * (0.5 * probability[1] + 1.0 * probability[2])
        let nearest = bestDist2[0].squareRoot()
        // Uzaklik cezasi: egitim verisinden uzak okumalar yuksek guven gostermesin.
        let distanceQuality = 1.0 / (1.0 + nearest / 3.0)

        return HydrationPrediction(
            hydrationClass: HydrationClass(rawValue: bestClass) ?? .low,
            probability: probability,
            wni: wni,
            confidence: 100 * probability[bestClass] * distanceQuality,
            nearestDistance: nearest
        )
    }
