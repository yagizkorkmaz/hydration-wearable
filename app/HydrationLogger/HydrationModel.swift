/// Su ihtiyaci sinifi. Ham deger `hydration_model.h` ile ayni:
/// 0 = LOW, 1 = MODERATE, 2 = HIGH.
enum HydrationClass: Int, CaseIterable, Hashable {
    case low = 0
    case moderate = 1
    case high = 2

    /// Modeldeki ingilizce etiket (CSV'ye bu yazilir).
    var rawName: String {
        switch self {
        case .low: return "LOW"
        case .moderate: return "MODERATE"
        case .high: return "HIGH"
        }
    }

    /// Ekranda gosterilen ad.
    var title: String {
        switch self {
        case .low: return "Low water need"
        case .moderate: return "Moderate water need"
        case .high: return "High water need"
        }
    }

    var shortTitle: String {
        switch self {
        case .low: return "LOW"
        case .moderate: return "MODERATE"
        case .high: return "HIGH"
        }
    }

    var subtitle: String {
        switch self {
        case .low: return "Hidrasyon iyi görünüyor"
        case .moderate: return "Su içmeyi düşün"
        case .high: return "Su iç"
        }
    }
}

/// `predictHydration()` ciktisinin Swift karsiligi.
struct HydrationPrediction: Hashable {
    let hydrationClass: HydrationClass
    /// LOW / MODERATE / HIGH sirasiyla siniflandirici agirliklari (toplami 1).
    let probability: [Double]
    /// Water Need Index, 0-100.
    let wni: Double
    /// Siniflandirici guveni (0-100). Klinik bir olasilik DEGIL.
    let confidence: Double
    /// En yakin egitim ornegine standartlastirilmis uzaklik.
    /// Buyuk deger = bu okuma egitim verisine benzemiyor.
    let nearestDistance: Double
}

