struct HydrationPrediction {
  uint8_t classId;
  float probability[3];
  float wni;
  float confidence;
  float nearestDistance;
};

inline const char* hydrationClassName(uint8_t classId) {
  switch (classId) {
    case 0: return "LOW";
    case 1: return "MODERATE";
    case 2: return "HIGH";
    default: return "UNKNOWN";
  }
}

inline HydrationPrediction predictHydration(const float features[HYD_FEATURE_COUNT]) {
  HydrationPrediction result;
  result.classId = 0;
  result.probability[0] = 0.0f;
  result.probability[1] = 0.0f;
  result.probability[2] = 0.0f;
  result.wni = -1.0f;
  result.confidence = 0.0f;
  result.nearestDistance = 999.0f;

  float z[HYD_FEATURE_COUNT];

  for (uint8_t j = 0; j < HYD_FEATURE_COUNT; j++) {
    const float denom = (HYD_FEATURE_STD[j] > 1e-9f)
      ? HYD_FEATURE_STD[j]
      : 1.0f;

    z[j] = (features[j] - HYD_FEATURE_MEAN[j]) / denom;
  }

  // Keep the K smallest SQUARED Euclidean distances.
  float bestDist2[HYD_K];
  uint8_t bestLabel[HYD_K];

  for (uint8_t k = 0; k < HYD_K; k++) {
    bestDist2[k] = 1e30f;
    bestLabel[k] = 0;
  }

  for (uint16_t i = 0; i < HYD_MODEL_SAMPLES; i++) {
    float d2 = 0.0f;

    for (uint8_t j = 0; j < HYD_FEATURE_COUNT; j++) {
      float diff = z[j] - HYD_MODEL_Z[i][j];
      d2 += diff * diff;
    }

    // Insertion into sorted K-best list.
    for (uint8_t k = 0; k < HYD_K; k++) {
      if (d2 < bestDist2[k]) {
        for (int m = HYD_K - 1; m > k; m--) {
          bestDist2[m] = bestDist2[m - 1];
          bestLabel[m] = bestLabel[m - 1];
        }

        bestDist2[k] = d2;
        bestLabel[k] = HYD_MODEL_LABEL[i];
        break;
      }
    }
  }

  float score[3] = {0.0f, 0.0f, 0.0f};

  for (uint8_t k = 0; k < HYD_K; k++) {
    // Weight = 1 / (d^2 + eps)
    float weight = 1.0f / (bestDist2[k] + 0.001f);
    score[bestLabel[k]] += weight;
  }

  float scoreSum = score[0] + score[1] + score[2];

  if (scoreSum <= 0.0f) {
    result.classId = 0;
    return result;
  }

  for (uint8_t c = 0; c < 3; c++) {
    result.probability[c] = score[c] / scoreSum;
  }

  uint8_t bestClass = 0;
  float bestProb = result.probability[0];

  for (uint8_t c = 1; c < 3; c++) {
    if (result.probability[c] > bestProb) {
      bestProb = result.probability[c];
      bestClass = c;
    }
  }

  result.classId = bestClass;

  // Relative Water-Need Index:
  // LOW=0, MODERATE=0.5, HIGH=1.0
  result.wni = 100.0f * (
    0.5f * result.probability[1] +
    1.0f * result.probability[2]
  );

  result.nearestDistance = sqrtf(bestDist2[0]);

  // Classifier-output confidence only; not a clinical probability.
  // Distance penalty prevents far-out samples from appearing overly certain.
  float distanceQuality = 1.0f / (1.0f + result.nearestDistance / 3.0f);
  result.confidence = 100.0f * bestProb * distanceQuality;

  return result;
}